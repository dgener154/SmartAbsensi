// Generate past 25 days of realistic attendance
export function generatePastAttendance(): StudentAttendance[] {
  const records: StudentAttendance[] = [];
  const today = new Date();
  
  // 25 active school days backwards (skipping Sundays)
  const schoolDates: string[] = [];
  let d = new Date(today);
  
  while (schoolDates.length < 22) {
    const dayOfWeek = d.getDay();
    if (dayOfWeek !== 0) { // skip Sunday
      const yyyy = d.getFullYear();
      const mm = String(d.getMonth() + 1).padStart(2, '0');
      const dd = String(d.getDate()).padStart(2, '0');
      schoolDates.unshift(`${yyyy}-${mm}-${dd}`);
    }
    d.setDate(d.getDate() - 1);
  }

  // Generate for VII-A, VII-B, VIII-A
  INITIAL_STUDENTS.forEach((student, studentIndex) => {
    schoolDates.forEach((dateStr, dateIdx) => {
      // Create pattern:
      // std-105 (Raffi) has frequent tardiness
      // std-109 (Ilham) has frequent sickness & alpa (low attendance < 80%)
      let status: 'HADIR' | 'TERLAMBAT' | 'IZIN' | 'SAKIT' | 'ALPA' = 'HADIR';
      let checkInTime = '06:55';
      let notes = '';

      if (student.id === 'std-109') {
        // Low attendance student for detection testing
        if (dateIdx % 3 === 0) {
          status = 'ALPA';
          checkInTime = '-';
          notes = 'Tanpa keterangan';
        } else if (dateIdx % 4 === 1) {
          status = 'SAKIT';
          checkInTime = '-';
          notes = 'Demam dan flu';
        } else if (dateIdx % 5 === 2) {
          status = 'TERLAMBAT';
          checkInTime = '07:22';
          notes = 'Macet di Ragunan';
        }
      } else if (student.id === 'std-105') {
        // Frequent tardiness student
        if (dateIdx % 4 === 0) {
          status = 'TERLAMBAT';
          checkInTime = '07:20';
          notes = 'Terlambat bangun';
        } else if (dateIdx % 7 === 1) {
          status = 'IZIN';
          checkInTime = '-';
          notes = 'Acara keluarga';
        }
      } else if (student.id === 'std-101' && dateIdx === schoolDates.length - 2) {
        status = 'IZIN';
        checkInTime = '-';
        notes = 'Izin takziyah';
      } else if (studentIndex % 5 === 0 && dateIdx % 6 === 2) {
        status = 'TERLAMBAT';
        checkInTime = '07:18';
        notes = 'Ban sepeda kempes';
      } else if (studentIndex % 7 === 0 && dateIdx % 8 === 3) {
        status = 'SAKIT';
        checkInTime = '-';
        notes = 'Surat dokter terlampir';
      }

      records.push({
        id: `att-${student.id}-${dateStr}`,
        date: dateStr,
        academicYearId: 'ay-2025-2026',
        semesterId: 'sem-1',
        classId: student.classId,
        subjectId: 'sb-mtk',
        scheduleId: 'sch-1',
        sessionId: 'ses-1',
        studentId: student.id,
        status,
        checkInTime,
        notes,
        recordedByTeacherId: 'tch-2',
        isLocked: dateIdx < schoolDates.length - 1, // lock past days, leave latest unlocked
        createdAt: `${dateStr}T07:10:00Z`,
        updatedAt: `${dateStr}T07:10:00Z`
      });
    });
  });

  return records;
}

